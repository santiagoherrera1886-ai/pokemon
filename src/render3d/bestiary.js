// Bestiario de la Bruma: las familias nuevas de Alborada (diseños propios inspirados en las láminas de
// concepto del proyecto) y las cuatro leyendas. Mismo método que creatures3d.js: S = cuerpo esculpido en
// una sola pieza, D = detalles (ojos, cristales, alas, llamas). Cada especie mira hacia +z y pisa y = 0.
import { Sculpt } from './sculpt.js';

const E = Sculpt.ellipsoid, C = Sculpt.roundCone;
const dir = (yaw, pitch) => [Math.cos(pitch) * Math.sin(yaw), Math.sin(pitch), Math.cos(pitch) * Math.cos(yaw)];
// Punto sobre la piel saliendo desde c (dentro del cuerpo) con giro y elevación; out lo despega un poco.
const at = (S, c, yaw, pitch, out = 0) => { const h = S.surface(c, dir(yaw, pitch)); return [h.p.x + h.n.x * out, h.p.y + h.n.y * out, h.p.z + h.n.z * out]; };
const lerp = (a, b, t) => a.map((v, i) => v + (b[i] - v) * t);
// Cuerpo de serpiente enroscado: espiral de segmentos que va de la punta de la cola (afuera) al cuello (adentro).
// Devuelve el último punto y deja pintadas las franjas cada cierto tramo.
const coil = (S, c, { r0, r1, turns, y0, y1, t0, t1, color, start = 0, bands, bandEvery = .12 }) => {
  const n = Math.ceil(turns * 14); let prev = null;
  for (let i = 0; i <= n; i++) {
    const u = i / n, a = start + u * turns * Math.PI * 2, r = r0 + (r1 - r0) * u;
    const p = [c[0] + Math.cos(a) * r, y0 + (y1 - y0) * u, c[2] + Math.sin(a) * r], th = t0 + (t1 - t0) * u;
    if (prev) S.limb(prev.p, p, prev.th, th, color, { k: .035 });
    prev = { p, th };
  }
  if (bands) for (let u = bandEvery * .6; u < 1; u += bandEvery) {
    const a = start + u * turns * Math.PI * 2, r = r0 + (r1 - r0) * u, th = t0 + (t1 - t0) * u;
    S.paint(E([c[0] + Math.cos(a) * r, y0 + (y1 - y0) * u, c[2] + Math.sin(a) * r], [th * .28, th * 1.5, th * 1.5], [0, -a, 0]), bands, th * .2);
  }
  return prev.p;
};

